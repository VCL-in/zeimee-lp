function PromptBox({ title, prompt }: { title: string; prompt: Prompt }) {
  return (
    <>
      <ColumnNote title={title}>
        {prompt.lines.map((line, i) => (
          <p key={i}>{line}</p>
        ))}
      </ColumnNote>
      <p>
        <strong>確認者（AIには入力しない）</strong>：{prompt.reviewer}
      </p>
    </>
  );
}

function ExternalLink({ href, children }: { href: string; children: string }) {
  return (
    <a href={href} target="_blank" rel="noopener noreferrer">
      {children}
    </a>
  );
}

